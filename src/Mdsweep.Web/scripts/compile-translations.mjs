import { readFile, mkdir, writeFile } from 'node:fs/promises';
import MessageFormat from '@messageformat/core';
import { parse } from '@messageformat/parser';
import compileModule from '@messageformat/core/compile-module.js';

// Re-running compilation during development should not cause a needless page reload.
async function writeIfChanged(url, content) {
  try {
    if ((await readFile(url, 'utf8')) === content) return;
  } catch {
    /* First compilation. */
  }
  await writeFile(url, content);
}

const root = new URL('../', import.meta.url);
const output = new URL('src/app/core/i18n/generated/', root);
await mkdir(output, { recursive: true });
const keys = (value, prefix = '') =>
  Object.entries(value)
    .flatMap(([key, item]) => {
      const path = prefix ? `${prefix}.${key}` : key;
      if (typeof item === 'string' && item.trim()) return [path];
      if (item && typeof item === 'object' && !Array.isArray(item)) return keys(item, path);
      throw new Error(`Translation ${path} must be a non-empty string.`);
    })
    .sort();
const parameters = (message) => {
  const names = new Set();
  const visit = (tokens) => {
    for (const token of tokens) {
      if (token.arg) names.add(token.arg);
      for (const branch of token.cases ?? []) visit(branch.tokens);
      if (token.param) visit(token.param);
    }
  };
  visit(parse(message));
  return [...names].sort();
};
const at = (catalog, key) => key.split('.').reduce((value, part) => value[part], catalog);
let englishKeys;
let englishCatalog;
for (const lang of ['en', 'ar']) {
  const catalog = JSON.parse(await readFile(new URL(`public/i18n/${lang}.json`, root), 'utf8'));
  const catalogKeys = keys(catalog);
  if (lang === 'en') {
    englishKeys = catalogKeys;
    englishCatalog = catalog;
  } else if (JSON.stringify(englishKeys) !== JSON.stringify(catalogKeys)) {
    throw new Error('English and Arabic catalogs must contain exactly the same keys.');
  }
  for (const key of catalogKeys) {
    if (
      JSON.stringify(parameters(at(catalog, key))) !==
      JSON.stringify(parameters(at(englishCatalog, key)))
    ) {
      throw new Error(`Translation parameters differ for ${key}.`);
    }
  }
  // Only the small MessageFormat runtime is shipped to the browser.
  const compiled = compileModule(new MessageFormat(lang), catalog);
  await writeIfChanged(
    new URL(`${lang}.js`, output),
    `// Generated by npm run i18n:compile. Edit public/i18n/${lang}.json.\n${compiled}\n`,
  );
  await writeIfChanged(
    new URL(`${lang}.d.ts`, output),
    "import type { InterpolatableTranslationObject } from '@ngx-translate/core';\ndeclare const catalog: InterpolatableTranslationObject;\nexport default catalog;\n",
  );
}
